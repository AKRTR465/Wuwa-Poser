[CmdletBinding()]
param([switch]$Check, [string]$SourcePath, [string]$OutputRoot)
$ErrorActionPreference = 'Stop'
Set-StrictMode -Version Latest
$repo = [IO.Path]::GetFullPath((Join-Path $PSScriptRoot '..'))
if (-not $SourcePath) { $SourcePath = Join-Path $repo 'playback/control_commands.json' }
if (-not $OutputRoot) { $OutputRoot = $repo }
$commands = @(Get-Content -LiteralPath $SourcePath -Raw -Encoding UTF8 | ConvertFrom-Json)
$ids = @{}; $names = @{}; $nativeNames = @{}
function Number($Value) { return ([double]$Value).ToString('R', [Globalization.CultureInfo]::InvariantCulture) }
foreach ($command in $commands) {
    if ($command.id -lt 1 -or $command.id -gt [uint32]::MaxValue -or $command.id -ne [math]::Truncate($command.id) -or
        $command.name -cnotmatch '^[a-z][a-z0-9_]*$' -or $command.native -cnotmatch '^[A-Z][A-Za-z0-9]*$' -or
        $ids.ContainsKey($command.id) -or $names.ContainsKey($command.name) -or $nativeNames.ContainsKey($command.native)) { throw 'Invalid or duplicate control command identity.' }
    if ($command.type -notin @('none', 'boolean', 'integer', 'number') -or $command.scope -notin @('session', 'actor', 'scene') -or
        -not [double]::IsFinite($command.min) -or ($null -ne $command.max -and (-not [double]::IsFinite($command.max) -or $command.max -lt $command.min)) -or
        ($command.type -eq 'none' -and ($command.min -ne 0 -or $command.max -ne 0)) -or
        ($command.type -eq 'boolean' -and ($command.min -ne 0 -or $command.max -ne 1))) { throw ('Invalid control command rule: ' + $command.name) }
    $ids[$command.id] = $true; $names[$command.name] = $true; $nativeNames[$command.native] = $true
}
$banner = '// Generated by tools/generate_playback_control.ps1 from playback/control_commands.json. DO NOT EDIT.'
$cpp = [Collections.Generic.List[string]]::new()
$cpp.Add($banner); $cpp.Add('#pragma once'); $cpp.Add('#include <cmath>'); $cpp.Add('#include <cstdint>'); $cpp.Add('namespace wwp_playback {')
$cpp.Add('enum class CommandKind : uint32_t {')
foreach ($command in $commands) { $cpp.Add(('    {0}={1},' -f $command.native, $command.id)) }
$cpp.Add('};'); $cpp.Add('inline bool IsActorCommand(CommandKind kind) noexcept {'); $cpp.Add('    switch(kind) {')
foreach ($command in $commands) { if ($command.scope -eq 'actor') { $cpp.Add('    case CommandKind::' + $command.native + ':') } }
$cpp.Add('        return true;'); $cpp.Add('    default:return false;'); $cpp.Add('    }'); $cpp.Add('}')
$cpp.Add('inline bool ValidCommandArguments(CommandKind kind,double value,uint32_t target_slot) noexcept {')
$cpp.Add('    if(!std::isfinite(value))return false;'); $cpp.Add('    switch(kind) {')
$cs = [Collections.Generic.List[string]]::new()
$cs.Add($banner); $cs.Add('namespace WWPoser.Services;'); $cs.Add('internal static class PlaybackCommands'); $cs.Add('{')
$cs.Add('    internal static uint Validate(string kind, double value, uint targetSlot)'); $cs.Add('    {')
$cs.Add('        var (id, minimum, maximum, integral, scene) = kind switch'); $cs.Add('        {')
$docs = [Collections.Generic.List[string]]::new()
$docs.Add('<!-- Generated by tools/generate_playback_control.ps1. DO NOT EDIT. -->'); $docs.Add('# 控制命令'); $docs.Add('')
$docs.Add('定义源为 `playback/control_commands.json`；执行 `pwsh tools/generate_playback_control.ps1` 更新两端代码与本表，使用 `-Check` 检查生成产物。所有 value 均以有限 IEEE754 binary64 传输，类型是其语义约束。'); $docs.Add('')
$docs.Add('`actor`：target_slot=0 广播，否则选择一个现有演员槽位。`scene`：只接受 target_slot=0。`session`：共享时间轴或镜头设置，建议 target_slot=0；保留 V1 非零槽位兼容（宿主检查槽位存在，但不会变成单演员时钟）。'); $docs.Add('')
$docs.Add('| 编号 | 命令 / C++ 名称 | 类型 | 单位 | 范围（含端点） | 作用域 | 含义 |'); $docs.Add('| --- | --- | --- | --- | --- | --- | --- |')
foreach ($command in $commands) {
    $min = Number $command.min; $max = if ($null -eq $command.max) { $null } else { Number $command.max }
    $integral = $command.type -in @('boolean', 'integer')
    $rules = @('value>=' + $min)
    if ($null -ne $max) { $rules += 'value<=' + $max }
    if ($integral) { $rules += 'std::trunc(value)==value' }
    if ($command.scope -eq 'scene') { $rules += 'target_slot==0' }
    $cpp.Add(('    case CommandKind::{0}:return {1};' -f $command.native, ($rules -join '&&')))
    $csMax = if ($null -eq $max) { 'double.PositiveInfinity' } else { $max + 'd' }
    $cs.Add(('            "{0}" => ({1}U, {2}d, {3}, {4}, {5}),' -f $command.name, $command.id, $min, $csMax, $integral.ToString().ToLowerInvariant(), ($command.scope -eq 'scene').ToString().ToLowerInvariant()))
    $range = if ($null -eq $max) { $min + '…∞' } elseif ($min -eq $max) { $min } else { $min + '…' + $max }
    $docs.Add(('| {0} | `{1}` / `{2}` | {3} | {4} | {5} | {6} | {7} |' -f $command.id, $command.name, $command.native, $command.type, $command.unit, $range, $command.scope, $command.description))
}
$cpp.Add('    }'); $cpp.Add('    return false;'); $cpp.Add('}'); $cpp.Add('} // namespace wwp_playback')
$cs.Add('            _ => throw new ArgumentException("未知控制命令：" + kind, nameof(kind))'); $cs.Add('        };')
$cs.Add('        if (scene && targetSlot != 0) throw new ArgumentException("全场命令不接受演员槽位：" + kind, nameof(targetSlot));')
$cs.Add('        if (!double.IsFinite(value) || value < minimum || value > maximum || (integral && Math.Truncate(value) != value))')
$cs.Add('            throw new ArgumentOutOfRangeException(nameof(value), $"{kind} 参数须为 [{minimum}, {maximum}] 内的{(integral ? "整数" : "有限数值")}");')
$cs.Add('        return id;'); $cs.Add('    }'); $cs.Add('}')
$outputs = [ordered]@{
    'playback/PlaybackCommands.generated.h' = $cpp -join "`n"
    'desktop/WWPoser/Generated/PlaybackCommands.generated.cs' = $cs -join "`n"
    'playback/CONTROL_COMMANDS.md' = $docs -join "`n"
}
foreach ($relative in $outputs.Keys) {
    $path = Join-Path $OutputRoot $relative
    $content = $outputs[$relative] + "`n"
    if ($Check) {
        if (-not (Test-Path -LiteralPath $path -PathType Leaf) -or [IO.File]::ReadAllText($path) -cne $content) { throw ('Stale generated control file: ' + $relative + '. Run tools/generate_playback_control.ps1.') }
    } elseif (-not (Test-Path -LiteralPath $path -PathType Leaf) -or [IO.File]::ReadAllText($path) -cne $content) {
        [IO.Directory]::CreateDirectory([IO.Path]::GetDirectoryName($path)) | Out-Null
        [IO.File]::WriteAllText($path, $content, [Text.UTF8Encoding]::new($false))
    }
}
Write-Output ('PASS: {0} control commands; {1} generated files{2}.' -f $commands.Count, $outputs.Count, $(if ($Check) { ' checked' } else { '' }))
